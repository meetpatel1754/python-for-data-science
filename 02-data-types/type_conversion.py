# String to Integer 
age = "20"
print(age)
print(type(age))
print("String to Integer")
age = int(age)
print(age)
print(type(age))
print("------------------")

# Integer to Float
marks = 95
print(marks)
print(type(marks))
print("Integer to Float")
marks = float(marks)
print(marks)
print(type(marks))
print("------------------")

# Float to Integer

height = 5.9
print(height)
print(type(height))
print("Float to Integer")
height = int(height)
print(height)
print(type(height))
print("------------------")

# Integer to String

year = 2026
print(year)
print(type(year))
print("Integer to String")
year = str(year)
print(year)
print(type(year))
print("------------------")

# Integer to Boolean

number = 1
print(number)
print(type(number))
print("Integer to Boolean")
number = bool(number)
print(number)
print(type(number))